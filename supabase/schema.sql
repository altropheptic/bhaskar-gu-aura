-- Security model
--   * The browser uses the PUBLISHABLE key -> requests run as the `anon` role.
--   * /api functions may use the SECRET key -> bypasses RLS, so only for trusted,
--     validated server-side operations.
--   * RLS is enabled on every table; anything not explicitly allowed is denied.
-- =============================================================================

